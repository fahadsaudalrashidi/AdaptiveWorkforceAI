def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _find_column(df: pd.DataFrame, pattern: re.Pattern) -> Optional[str]:
    for col in df.columns:
        if pattern.search(str(col)):
            return col
    return None


def _is_missing_value(raw: object) -> bool:
    """Same missing-value discipline as department_normalizer.py's
    _is_missing_department()."""
    if raw is None:
        return True
    try:
        if pd.isna(raw):
            return True
    except (TypeError, ValueError):
        pass
    return not str(raw).strip()


def safe_record_id_for_lookup(raw_id: Any) -> str:
    """
    Reproduces labor_law_calculators._safe_record_id()'s EXACT hash scheme
    (itself the same scheme as employee_risk_scoring._make_record_id()) so
    the ROUTE LAYER can compute the same key for a raw employee ID and join
    it against a GratuityCandidate.record_id_safe without either engine
    importing the other. This is the hash function only — not gratuity math.
    """
    h = hashlib.sha256(str(raw_id).encode()).hexdigest()[:6].upper()
    return f"EMP-{h}"


def _extract_strict_numeric(raw: object) -> Optional[float]:
    """Same strict "clean number or nothing" rule as
    labor_law_calculators._extract_strict_numeric_salary(), reproduced
    locally per this codebase's per-module convention (see module
    docstring). A salary certificate's figure is exactly the same kind of
    legally-relevant number that module refuses to approximate."""
    if _is_missing_value(raw):
        return None
    val = pd.to_numeric(raw, errors="coerce")
    if pd.isna(val) or float(val) <= 0:
        return None
    return float(val)


def _format_hire_date(raw: object) -> str:
    """Best-effort human-readable date; falls back to the raw string
    verbatim rather than fabricating a date if it cannot be parsed."""
    if _is_missing_value(raw):
        return ""
    parsed = pd.to_datetime(raw, errors="coerce")
    if pd.notna(parsed):
        return parsed.strftime("%d %B %Y")
    return str(raw).strip()


def _fmt_sar(amount: float) -> str:
    return f"SAR {amount:,.2f}"


# ── Mixed-script bidi handling (Phase 38 fix, see module docstring) ────────

_LATIN_CHARS_PATTERN = re.compile(r"[A-Za-z]")
_ARABIC_CHARS_PATTERN = re.compile(r"[؀-ۿݐ-ݿ]")
_LRI, _RLI, _PDI = "⁦", "⁧", "⁩"  # LEFT/RIGHT-TO-LEFT ISOLATE, POP DIRECTIONAL ISOLATE


def _bidi_isolate(text: str, language: str) -> str:
    """Wraps `text` in Unicode directional-isolate marks when its script
    doesn't match the surrounding paragraph's language, so Word renders it
    with correct spacing/flow instead of the broken mid-sentence splicing
    live testing found (see module docstring). Never translates or alters
    the text itself — isolation only."""
    if not text:
        return text
    if language == "ar" and _LATIN_CHARS_PATTERN.search(text):
        return f"{_LRI}{text}{_PDI}"
    if language != "ar" and _ARABIC_CHARS_PATTERN.search(text):
        return f"{_RLI}{text}{_PDI}"
    return text


def _translate_department_for_letter(department: str, language: str) -> str:
    """Reuses department_normalizer.py's curated EN_AR_DEPARTMENT_SYNONYMS
    table (real reuse, not a new translation table) to render a common
    department name in Arabic. Falls back to the original value — never
    fabricated — when no curated mapping exists for this exact canonical
    label. Job titles are open free text and are never translated (see
    module docstring); they are LTR/RTL-isolated instead via
    _bidi_isolate()."""
    if language != "ar":
        return department
    variants = EN_AR_DEPARTMENT_SYNONYMS.get(department)
    if not variants:
        return department
    arabic_variant = next((v for v in variants if _ARABIC_CHARS_PATTERN.search(v)), None)
    return arabic_variant or department


