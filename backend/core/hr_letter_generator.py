def _set_rtl_paragraph(paragraph) -> None:
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pPr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement("w:bidi")
    pPr.append(bidi)
    for run in paragraph.runs:
        _set_rtl_run(run)


def _set_rtl_run(run) -> None:
    rPr = run._r.get_or_add_rPr()
    rtl = OxmlElement("w:rtl")
    rPr.append(rtl)
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:cs"), "Arial")


def _add_para(doc: Document, text: str, *, language: str, bold: bool = False,
              size: int = 11, color: Optional[RGBColor] = None,
              align_center: bool = False, space_after: int = 8):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    if color is not None:
        run.font.color.rgb = color
    p.paragraph_format.space_after = Pt(space_after)
    if language == "ar":
        _set_rtl_paragraph(p)
    if align_center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p


def _add_horizontal_rule(doc: Document) -> None:
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "8")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "1F2937")
    pBdr.append(bottom)
    pPr.append(pBdr)


def _set_section_rtl(doc: Document) -> None:
    sectPr = doc.sections[0]._sectPr
    bidi = OxmlElement("w:bidi")
    sectPr.append(bidi)


def _new_letter_document(company: CompanyDetails, language: str, letter_type: str,
                          employee_id: str) -> Document:
    doc = Document()
    if language == "ar":
        _set_section_rtl(doc)

    _add_para(doc, company.company_name, language=language, bold=True, size=16)
    _add_para(doc, company.company_address, language=language, size=9.5, space_after=10)
    _add_horizontal_rule(doc)

    today = datetime.now(timezone.utc).strftime("%d %B %Y")
    ref = f"Ref: {_REF_PREFIX[letter_type]}-{employee_id}-{datetime.now(timezone.utc).strftime('%Y%m%d')}"
    if language == "ar":
        _add_para(doc, f"التاريخ: {today}", language=language, size=10)
        _add_para(doc, ref, language=language, size=10, space_after=14)
        _add_para(doc, _SUBJECT_AR[letter_type], language=language, bold=True, size=14, align_center=True)
        _add_para(doc, "إلى من يهمه الأمر،", language=language, bold=True, space_after=12)
    else:
        _add_para(doc, f"Date: {today}", language=language, size=10)
        _add_para(doc, ref, language=language, size=10, space_after=14)
        _add_para(doc, _SUBJECT_EN[letter_type], language=language, bold=True, size=14, align_center=True)
        _add_para(doc, "To Whom It May Concern,", language=language, bold=True, space_after=12)
    return doc


def _add_signature_block(doc: Document, company: CompanyDetails, language: str) -> None:
    _add_para(doc, "", language=language, space_after=12)
    if language == "ar":
        _add_para(doc, "مع خالص التقدير،", language=language, space_after=24)
        _add_para(doc, "التوقيع: ________________________", language=language)
        _add_para(doc, company.signatory_name, language=language, bold=True, space_after=0)
        _add_para(doc, company.signatory_title, language=language, space_after=0)
        _add_para(doc, company.company_name, language=language, space_after=12)
    else:
        _add_para(doc, "Sincerely,", language=language, space_after=24)
        _add_para(doc, "Signature: ________________________", language=language)
        _add_para(doc, company.signatory_name, language=language, bold=True, space_after=0)
        _add_para(doc, company.signatory_title, language=language, space_after=0)
        _add_para(doc, company.company_name, language=language, space_after=12)


def _add_draft_marking(doc: Document, language: str) -> None:
    text = DRAFT_REVIEW_MARK_AR if language == "ar" else DRAFT_REVIEW_MARK_EN
    _add_para(doc, text, language=language, bold=True, size=10.5,
              color=RGBColor(0xB4, 0x1E, 0x1E), align_center=True, space_after=6)


def _add_footer_note(doc: Document, language: str) -> None:
    generated_on = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    if language == "ar":
        note = (
            f"تم إنشاء هذه الوثيقة تلقائياً بواسطة منصة Adaptive Workforce AI بتاريخ "
            f"{generated_on} من البيانات المُحمّلة — وهي مسودة وليست سجلاً موقعاً أصلياً من "
            "الموارد البشرية."
        )
    else:
        note = (
            f"This document was automatically generated by the Adaptive Workforce AI "
            f"platform on {generated_on} from uploaded data — it is a draft, not an "
            "original signed HR record."
        )
    _add_horizontal_rule(doc)
    _add_para(doc, note, language=language, size=8, color=RGBColor(0x6B, 0x72, 0x80), space_after=0)


def _finalize_document(doc: Document, language: str) -> bytes:
    _add_draft_marking(doc, language)
    _add_footer_note(doc, language)
    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _safe_filename_fragment(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", text).strip("_") or "employee"


