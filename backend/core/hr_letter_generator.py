"""
Automated HR Letter Generator — Phase 36.

Produces common official employee letters (Word documents) from uploaded
employee data — a mail-merge style feature common on established Saudi HR
platforms. This module is deliberately different from every other module
this session: its entire purpose is to produce real, NAMED, official
correspondence, so it does not anonymize record_id_safe-style — that would
defeat the purpose. The safety discipline instead shifts to three rules,
enforced throughout this file:

1. Only letter types with genuinely low legal/disciplinary risk are offered.
   Warning/disciplinary letters (خطاب إنذار) and termination letters are
   deliberately NOT built here, and never will be added "for completeness."
   Both require a case-specific, human judgment call about employee conduct
   or separation circumstances that this platform has no reliable data to
   support — a Salary Certificate or Employment Certificate only restates
   facts already present in the uploaded data (position, tenure, pay); a
   warning letter would require this platform to assert something about an
   employee's conduct it cannot know. Getting a disciplinary/termination
   letter wrong has real legal exposure for the issuing company and the
   named employee; getting a salary certificate's numbers right (or
   honestly declining, see rule 2) is a bounded, checkable task.
2. Nothing is ever fabricated or inferred beyond what the uploaded row
   contains. The Salary Certificate specifically reuses the exact strict
   numeric-salary discipline `labor_law_calculators.py` established for
   Article 84/111 legal figures (never a range-text midpoint) — a salary
   figure written into an official bank/visa-facing certificate is exactly
   the same kind of "real legally-relevant number" that module's docstring
   describes, so the same rule applies here: if the salary column isn't a
   clean number, the certificate honestly states it cannot include an exact
   figure rather than generating one anyway. The `_extract_strict_numeric`
   helper below is a small local reimplementation of that same rule (not a
   cross-import of `labor_law_calculators._extract_strict_numeric_salary`,
   which is a private, underscore-prefixed helper never meant to cross a
   module boundary — the same "duplicate small detection/extraction
   helpers per module" convention `job_pattern_grouping_engine.py` and
   `contract_expiry_engine.py` both document and follow).
3. Every generated letter carries a prominent "DRAFT — Requires Review &
   Authorized Signature" marking (top and bottom of the document) plus a
   footer disclosing it was generated by this platform from uploaded data,
   not an original signed HR record. This platform has no way to verify the
   uploader has actual authority to issue official company correspondence,
   so every document is unambiguously a draft pending human sign-off.

**End-of-Service Settlement cross-link — route-layer decoupling, not a
direct import.** This module does NOT import `labor_law_calculators.py`,
and that module does not import this one — the identical architectural
choice `contract_expiry_engine.py` and `succession_readiness_engine.py`
made for their Phase 8/18 cross-links (see both modules' docstrings). The
route layer (`local_analysis_routes.py`, which already imports every engine
independently) is the only place that runs BOTH `analyze_gratuity()` and
`extract_employee_letter_records()` on the SAME uploaded file and joins
their results by `record_id_safe` — the exact join key
`labor_law_calculators._safe_record_id()` already produces
(`sha256(raw_id)[:6].upper()`, `"EMP-"`-prefixed; reproduced locally here
as `safe_record_id_for_lookup()` purely so the route layer can compute the
SAME hash for a raw employee ID and match it against a `GratuityCandidate`
— this is the hash function, not the gratuity math, so reproducing it is
not a legal-formula duplication). `build_end_of_service_letter()` below
never computes a gratuity figure itself — it only accepts one as a
parameter and formats it into a letter, so the real Article 84/85 math
lives in exactly one place: `labor_law_calculators.py`.

**Column detection reuses this session's existing patterns verbatim where
one already exists** (job title from `job_pattern_grouping_engine.py`,
hire date from `recruitment_pipeline_engine.py`, salary/department from
`labor_law_calculators.py` / `pay_equity_engine.py`) — duplicated locally
per this codebase's established per-module convention, not cross-imported.
An employee NAME column is a genuinely new detection target for this
session (every prior module deliberately avoided reading one) —
`_NAME_PATTERNS` below is new.

**Phase 38 correction — mixed-script bidi rendering fix, plus department
translation.** Live testing found generated letters could render with
visibly broken spacing/flow wherever a value in one script was interpolated
inline into a sentence written in the other script (e.g. an Arabic company
name inside an English sentence, or an English department/job title inside
an Arabic sentence) — a genuine Word bidi-rendering defect, reproduced and
confirmed via `python-docx` paragraph text inspection during investigation,
not a "language selector doesn't work" bug (the language branch selection
itself was verified correct end to end, including a live network-level
check that the frontend's language toggle really does change the `language`
form field it POSTs). Fixed two ways:

1. **Department translation** — `_translate_department_for_letter()` below
   REUSES `department_normalizer.py`'s `EN_AR_DEPARTMENT_SYNONYMS` curated
   table directly (real reuse, not a new translation list) to render common
   department names in Arabic when generating an Arabic letter. Falls back
   to the original (English) value, never fabricated, when the employee's
   canonical department isn't one of that table's curated keys.
2. **LTR/RTL isolation for everything else** — job titles are open free
   text this platform cannot reliably translate (unlike the small, bounded
   department vocabulary), so instead of translating them,
   `_bidi_isolate()` below wraps any inline-interpolated value with Unicode
   directional-isolate marks (U+2066/U+2067 ... U+2069) whenever its script
   doesn't match the paragraph's language — the same "isolate rather than
   guess a translation" principle `LatinText.tsx`
   (`executive-ui/src/components/shared/LatinText.tsx`) already established
   for this platform's RTL tables (`dir="ltr"` + `unicode-bidi: isolate`
   for Latin text inside an RTL context); this is that same technique's
   text-level equivalent, applied symmetrically in both directions since a
   user can type either script into the company-details form regardless of
   which document language they select.
"""

