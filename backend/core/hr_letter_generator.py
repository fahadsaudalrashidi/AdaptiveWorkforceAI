def extract_employee_letter_records(df: pd.DataFrame) -> EmployeeDataResult:
    """Never raises — exceptions should be caught by the caller and surfaced
    via unavailable_employee_data_result."""
    if df is None or df.empty:
        return unavailable_employee_data_result("No data available.")

    name_col = _find_column(df, _NAME_PATTERNS)
    id_col = next((c for c in _ID_COLUMN_CANDIDATES if c in df.columns), None)
    title_col = _find_column(df, _JOB_TITLE_PATTERNS)
    dept_col = _find_column(df, _DEPARTMENT_PATTERNS)
    hire_col = _find_column(df, _HIRE_DATE_PATTERNS)
    salary_col = _find_column(df, _SALARY_PATTERNS)

    columns_detected = {
        "name": name_col is not None,
        "employee_id": id_col is not None,
        "job_title": title_col is not None,
        "department": dept_col is not None,
        "hire_date": hire_col is not None,
        "salary": salary_col is not None,
    }

    missing = [k for k in ("name", "employee_id", "job_title", "department", "hire_date") if not columns_detected[k]]
    if missing:
        return unavailable_employee_data_result(
            f"Official letters require {', '.join(missing)} column(s), none of which can be "
            "assumed or fabricated for a real official document.",
            columns_detected,
        )

    dept_result = normalize_department_series(df[dept_col].astype(object))
    dept_keys = pd.Series(dept_result.normalized_keys.values, index=df.index)

    employees: list[EmployeeLetterRecord] = []
    n_excluded_required = 0
    n_excluded_salary = 0
    for idx in df.index:
        raw_name = df.at[idx, name_col]
        raw_id = df.at[idx, id_col]
        raw_title = df.at[idx, title_col]
        raw_dept = df.at[idx, dept_col]
        raw_hire = df.at[idx, hire_col]

        if any(_is_missing_value(v) for v in (raw_name, raw_id, raw_title, raw_dept, raw_hire)):
            n_excluded_required += 1
            continue

        dept_display = dept_result.display_labels.get(dept_keys.loc[idx], str(raw_dept).strip())

        salary_val: Optional[float] = None
        salary_raw_display: Optional[str] = None
        if salary_col is not None:
            raw_salary = df.at[idx, salary_col]
            if not _is_missing_value(raw_salary):
                salary_val = _extract_strict_numeric(raw_salary)
                if salary_val is None:
                    salary_raw_display = str(raw_salary).strip()
                    n_excluded_salary += 1

        employees.append(EmployeeLetterRecord(
            row_key=idx,
            employee_id=str(raw_id).strip(),
            name=str(raw_name).strip(),
            job_title=str(raw_title).strip(),
            department=dept_display,
            hire_date_display=_format_hire_date(raw_hire),
            salary_sar=salary_val,
            salary_raw_display=salary_raw_display,
        ))

    if not employees:
        return unavailable_employee_data_result(
            f"Found name ('{name_col}'), ID ('{id_col}'), job title ('{title_col}'), "
            f"department ('{dept_col}'), and hire date ('{hire_col}') columns, but no "
            "single row had a usable (non-missing) value in every one of them.",
            columns_detected,
        )

    narrative_en = (
        f"{len(employees)} of {len(df)} employee row(s) have all fields required for "
        f"official letters (name, ID, job title, department, hire date)."
    )
    narrative_ar = (
        f"لدى {len(employees)} من أصل {len(df)} صفاً كل الحقول المطلوبة للخطابات الرسمية "
        "(الاسم، المعرّف، المسمى الوظيفي، القسم، تاريخ التعيين)."
    )
    if n_excluded_required > 0:
        narrative_en += f" {n_excluded_required} row(s) excluded — a required field was missing."
        narrative_ar += f" استُبعد {n_excluded_required} صفاً — حقل مطلوب مفقود."
    if salary_col is None:
        narrative_en += " No salary column detected — Salary Certificates are unavailable for this dataset."
        narrative_ar += " لم يتم اكتشاف عمود راتب — خطابات تعريف الراتب غير متاحة لهذه البيانات."
    elif n_excluded_salary > 0:
        narrative_en += f" {n_excluded_salary} employee(s) have a non-numeric salary value — Salary Certificates unavailable for them specifically."
        narrative_ar += f" لدى {n_excluded_salary} موظفاً قيمة راتب غير رقمية — خطاب تعريف الراتب غير متاح لهم تحديداً."

    return EmployeeDataResult(
        available=True, reason=None, columns_detected=columns_detected,
        name_column=name_col, employee_id_column=id_col, job_title_column=title_col,
        department_column=dept_col, hire_date_column=hire_col, salary_column=salary_col,
        n_total_rows=len(df), n_usable=len(employees),
        n_excluded_missing_required=n_excluded_required, n_excluded_invalid_salary=n_excluded_salary,
        employees=employees,
        narrative_en=narrative_en, narrative_ar=narrative_ar,
        excluded_letter_types_note_en=EXCLUDED_LETTER_TYPES_NOTE_EN,
        excluded_letter_types_note_ar=EXCLUDED_LETTER_TYPES_NOTE_AR,
        governance_note=(
            "Unlike every other module on this platform, letters generated here include "
            "real employee names and IDs by necessity — that is this module's entire "
            "purpose. Every generated document carries a prominent draft/review marking; "
            "this platform cannot verify the uploader has authority to issue official "
            "company correspondence."
        ),
        computed_at=_now(),
    )


