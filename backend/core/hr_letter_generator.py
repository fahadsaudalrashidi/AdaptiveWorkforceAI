@dataclass(frozen=True)
class GratuityLetterInput:
    """What the route layer passes in per-employee for the end-of-service
    letter type, joined from labor_law_calculators.analyze_gratuity()'s
    output by record_id_safe — see module docstring."""
    gratuity_amount_sar: float
    gratuity_scenario: str
    years_of_service: float
    monthly_wage_sar: float
    wage_column_name: str
    gratuity_computed_at: str


@dataclass(frozen=True)
class BulkLetterItemStatus:
    employee_id: str
    name: str
    generated: bool
    reason: Optional[str]
    filename: Optional[str]


@dataclass(frozen=True)
class BulkLetterResult:
    letter_type: str
    n_requested: int
    n_generated: int
    n_skipped: int
    items: list[BulkLetterItemStatus]
    zip_bytes: Optional[bytes]


def build_bulk_letters(
    employees: list[EmployeeLetterRecord],
    letter_type: str,
    company: CompanyDetails,
    language: str,
    gratuity_lookup: Optional[dict[str, GratuityLetterInput]] = None,
) -> BulkLetterResult:
    """One document per employee (mail-merge pattern), zipped together.
    Skips (never fabricates for) any employee the specific letter type
    isn't available for, and reports exactly why per employee."""
    employees = employees[:_MAX_BULK_EMPLOYEES]
    gratuity_lookup = gratuity_lookup or {}
    items: list[BulkLetterItemStatus] = []
    zip_buf = BytesIO()
    n_generated = 0

    with zipfile.ZipFile(zip_buf, "w", zipfile.ZIP_DEFLATED) as zf:
        used_names: set[str] = set()
        for emp in employees:
            if letter_type == "salary_certificate":
                result = build_salary_certificate(emp, company, language)
            elif letter_type == "employment_certificate":
                result = build_employment_certificate(emp, company, language)
            elif letter_type == "end_of_service_settlement":
                gi = gratuity_lookup.get(emp.employee_id)
                if gi is None:
                    result = LetterBuildResult(
                        available=False,
                        reason=(
                            "End-of-Service Gratuity is not computable for this employee — "
                            "requires both a clean numeric salary and a clean numeric "
                            "years-of-service value (see the Saudi Labor Law Calculators "
                            "module)."
                        ),
                        letter_type=letter_type, employee_id=emp.employee_id,
                        filename=None, document_bytes=None,
                    )
                else:
                    result = build_end_of_service_letter(
                        emp, company, language,
                        gratuity_amount_sar=gi.gratuity_amount_sar,
                        gratuity_scenario=gi.gratuity_scenario,
                        years_of_service=gi.years_of_service,
                        monthly_wage_sar=gi.monthly_wage_sar,
                        wage_column_name=gi.wage_column_name,
                        gratuity_computed_at=gi.gratuity_computed_at,
                    )
            else:
                result = LetterBuildResult(
                    available=False, reason=f"Unknown letter type {letter_type!r}.",
                    letter_type=letter_type, employee_id=emp.employee_id,
                    filename=None, document_bytes=None,
                )

            if result.available and result.document_bytes is not None:
                arcname = result.filename or f"{letter_type}_{emp.employee_id}.docx"
                if arcname in used_names:
                    arcname = f"{arcname[:-5]}_{emp.row_key}.docx"
                used_names.add(arcname)
                zf.writestr(arcname, result.document_bytes)
                n_generated += 1
            items.append(BulkLetterItemStatus(
                employee_id=emp.employee_id, name=emp.name, generated=result.available,
                reason=result.reason, filename=result.filename if result.available else None,
            ))

    zip_bytes = zip_buf.getvalue() if n_generated > 0 else None
    return BulkLetterResult(
        letter_type=letter_type, n_requested=len(employees), n_generated=n_generated,
        n_skipped=len(employees) - n_generated, items=items, zip_bytes=zip_bytes,
    )


def bulk_letter_result_to_dict(r: BulkLetterResult) -> dict[str, Any]:
    return {
        "letter_type": r.letter_type, "n_requested": r.n_requested,
        "n_generated": r.n_generated, "n_skipped": r.n_skipped,
        "items": [
            {"employee_id": i.employee_id, "name": i.name, "generated": i.generated,
             "reason": i.reason, "filename": i.filename}
            for i in r.items
        ],
    }
