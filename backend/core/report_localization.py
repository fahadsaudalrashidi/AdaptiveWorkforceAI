"""
Report Localization — Phase 9.

Provides bilingual (Arabic / English) text for all report sections,
labels, disclaimers, and governance notices used in executive report export.

Design rules:
  - All strings exist in both 'en' and 'ar'
  - No machine translation — all Arabic text is hand-authored
  - Direction metadata included for PDF layout
  - Governance disclaimers cannot be suppressed or translated away
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

Language = Literal["en", "ar"]


@dataclass(frozen=True)
class BilingualString:
    en: str
    ar: str

    def get(self, lang: Language) -> str:
        return self.ar if lang == "ar" else self.en


