# ── ReportLocalizer ───────────────────────────────────────────────────────────

class ReportLocalizer:
    """
    Provides localized strings for report generation.

    Usage:
        loc = ReportLocalizer("ar")
        title = loc.label("report_executive_summary")
        disclaimer = loc.governance_disclaimer()
    """

    def __init__(self, language: Language = "en") -> None:
        if language not in ("en", "ar"):
            raise ValueError(f"Unsupported language: {language!r}. Use 'en' or 'ar'.")
        self.language = language

    def label(self, key: str, fallback: str = "") -> str:
        if key not in LABELS:
            return fallback or key
        return LABELS[key].get(self.language)

    def governance_disclaimer(self) -> str:
        return GOVERNANCE_DISCLAIMER.get(self.language)

    def confidence_warning(self) -> str:
        return CONFIDENCE_WARNING.get(self.language)

    def pdpl_note(self) -> str:
        return PDPL_NOTE.get(self.language)

    def all_disclaimers(self) -> list[str]:
        return [
            self.governance_disclaimer(),
            self.confidence_warning(),
            self.pdpl_note(),
        ]

    def construct_label(self, construct_key: str) -> str:
        if construct_key in CONSTRUCTS:
            return CONSTRUCTS[construct_key].get(self.language)
        return construct_key

    def governance_lock_label(self, lock_key: str) -> str:
        if lock_key in GOVERNANCE_LOCKS:
            return GOVERNANCE_LOCKS[lock_key].get(self.language)
        return lock_key

    def pdf_layout(self) -> dict:
        return PDF_LAYOUT[self.language]

    @property
    def is_rtl(self) -> bool:
        return self.language == "ar"
